import smtplib
import os
from email.mime.text import MIMEText
from datetime import datetime

# Load credentials from environment variables.
# Copy .env.example to .env and fill in your real values.
# See SECURITY.md — never hardcode credentials in source files.
SENDER_EMAIL = os.environ.get("SENDER_EMAIL", "your_email@gmail.com")
SENDER_PASSWORD = os.environ.get("SENDER_PASSWORD", "your_gmail_app_password_here")
RECEIVER_EMAIL = os.environ.get("RECEIVER_EMAIL", "alert_receiver@example.com")

def send_email_alert(message):
    try:
        subject = "Cloud Forensic Alert Notification"

        body = f"""
        ALERT DETECTED

        Time: {datetime.now()}
        Alert: {message}

        This alert was generated by Cloud Forensic Investigation Tool.
        """

        msg = MIMEText(body)
        msg['Subject'] = subject
        msg['From'] = SENDER_EMAIL
        msg['To'] = RECEIVER_EMAIL

        server = smtplib.SMTP('smtp.gmail.com', 587)
        server.starttls()
        server.login(SENDER_EMAIL, SENDER_PASSWORD)
        server.sendmail(SENDER_EMAIL, RECEIVER_EMAIL, msg.as_string())
        server.quit()

        print("Email alert sent")

    except Exception as e:
        print("Email sending failed:", e)